-- v2: what the core did in Todoist for each message or tick-off (v1 kept it as text in the log call's todoist field).
-- raw_inbox stays insert-only; undo and the retry of waiting items read this table. batch groups one message's
-- actions (r<raw id>) or one tick-off command (c<hex>).
BEGIN;

CREATE TABLE todo_actions (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch      text NOT NULL,
  raw_id     bigint REFERENCES raw_inbox(id),
  op         text NOT NULL CHECK (op IN ('exists','reopened','created','closed','waiting')),
  item       text NOT NULL,              -- the item as the parser named it (English)
  task_id    text,                       -- Todoist's id; NULL while waiting
  content    text,                       -- the task's name in Todoist
  place      text,                       -- project, section and label, for receipts
  payload    jsonb,                      -- waiting: the parser's item, to send again
  at         timestamptz NOT NULL DEFAULT now(),
  undone_at  timestamptz
);
CREATE INDEX todo_actions_batch_idx ON todo_actions (batch);
CREATE INDEX todo_actions_waiting_idx ON todo_actions (at) WHERE op = 'waiting' AND undone_at IS NULL;

GRANT SELECT, INSERT, UPDATE ON todo_actions TO core_rw;
GRANT USAGE, SELECT ON SEQUENCE todo_actions_id_seq TO core_rw;

COMMIT;