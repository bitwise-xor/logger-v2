-- Copied from logger-app sql/schema-v2.sql (v1 schema v2). Only change: role mcp_writer -> core_rw, NocoDB grants removed.
-- Thought inbox, schema v2 (simplified). DRAFT, NOT YET RUN.
-- Run as app_owner in database appdata. Later changes: additive only.
-- Test tables (test_items, raw_inbox_test, ideas_test) are dropped after the import, not here.
-- Rules this schema assumes:
--   * The server routes by label: message starting "private:" or "gratitude:" -> private.entries only.
--   * One message, one tier.
--   * Undo = delete the derived row; the verbatim message stays in raw_inbox.
--   * Duplicates = link 'duplicate_of' + stage 'dropped'.

BEGIN;

-- ============ general side ============

-- Verbatim capture. Never edited. Never exposed to NocoDB.
CREATE TABLE raw_inbox (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  received_at timestamptz NOT NULL DEFAULT now(),
  channel     text NOT NULL,                 -- claude-chat, import, telegram, web
  content     text NOT NULL,                 -- the message exactly as typed
  is_import   boolean NOT NULL DEFAULT false,
  import_ref  text,                          -- e.g. 'Brain Storming/Ideas/#7'
  metadata    jsonb NOT NULL DEFAULT '{}'    -- original sheet row, image note ...
);

-- One row per thought; one message can produce several.
-- BY DEFAULT so the import can keep the old numbers #1..#24. After the import run:
--   SELECT setval(pg_get_serial_sequence('thoughts','id'), (SELECT max(id) FROM thoughts));
CREATE TABLE thoughts (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raw_id            bigint NOT NULL REFERENCES raw_inbox(id),
  original_text     text NOT NULL,           -- user's wording for this thought
  summary           text NOT NULL,           -- cleaned one-line version
  thought_type      text CHECK (thought_type IN
                      ('idea','question','task','project','note','journal','reading','progress')),
                                             -- NULL = unsorted
  next_step         text CHECK (next_step IN ('research','plan','do','read')),
  area              text CHECK (area IN
                      ('health','projects','finance','immigration','learning','personal')),
  tags              text[] NOT NULL DEFAULT '{}',
  aliases           text[] NOT NULL DEFAULT '{}',  -- project rows only ('app logger')
  stage             text NOT NULL DEFAULT 'inbox' CHECK (stage IN
                      ('inbox','active','someday','done','dropped')),
  event_at          timestamptz,             -- when it happened (NULL = same as logged)
  logged_at         timestamptz NOT NULL DEFAULT now(),
  source            text CHECK (source IN ('chat','document','link','image')),
  source_detail     text,                    -- 'photo of a whiteboard', a URL ...
  needs_review      boolean NOT NULL DEFAULT false,
  review_reason     text,
  confidence        numeric(3,2) CHECK (confidence BETWEEN 0 AND 1),
  extractor_version text
);
CREATE INDEX thoughts_stage_idx   ON thoughts (stage);
CREATE INDEX thoughts_tags_idx    ON thoughts USING gin (tags);
CREATE INDEX thoughts_aliases_idx ON thoughts USING gin (aliases);
CREATE INDEX thoughts_fts_idx     ON thoughts USING gin
  (to_tsvector('simple', summary || ' ' || original_text));

-- Follow-ups: a small timeline per thought.
CREATE TABLE thought_updates (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  thought_id  bigint NOT NULL REFERENCES thoughts(id) ON DELETE CASCADE,
  raw_id      bigint REFERENCES raw_inbox(id),
  update_text text NOT NULL,
  event_at    timestamptz,
  logged_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX thought_updates_thought_idx ON thought_updates (thought_id);

-- Typed links, stored once, read both ways.
-- 'related' is symmetric: stored with from_id < to_id so it cannot exist twice.
CREATE TABLE thought_links (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  from_id    bigint NOT NULL REFERENCES thoughts(id) ON DELETE CASCADE,
  to_id      bigint NOT NULL REFERENCES thoughts(id) ON DELETE CASCADE,
  link_type  text NOT NULL CHECK (link_type IN
               ('part_of','follow_up_of','related','completes','duplicate_of')),
  added_by   text NOT NULL DEFAULT 'claude' CHECK (added_by IN ('claude','user','import')),
  reviewed   boolean NOT NULL DEFAULT false,   -- ticked in the weekly review
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (from_id <> to_id),
  CHECK (link_type <> 'related' OR from_id < to_id),
  UNIQUE (from_id, to_id, link_type)
);
CREATE INDEX thought_links_to_idx ON thought_links (to_id);

-- ============ private tier ============
-- One table: verbatim message and its classification in the same row.
-- No links, no updates. NocoDB gets no access to this schema (fails closed).

CREATE SCHEMA private;
REVOKE ALL ON SCHEMA private FROM PUBLIC;

CREATE TABLE private.entries (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  received_at   timestamptz NOT NULL DEFAULT now(),
  channel       text NOT NULL,
  label         text NOT NULL CHECK (label IN ('private','gratitude')),
  content       text NOT NULL,               -- verbatim message, never edited
  summary       text,                        -- may stay NULL (no LLM on some channels)
  thought_type  text CHECK (thought_type IN
                  ('idea','question','task','project','note','journal','reading','progress')),
  area          text CHECK (area IN
                  ('health','projects','finance','immigration','learning','personal')),
  tags          text[] NOT NULL DEFAULT '{}',
  event_at      timestamptz,
  is_import     boolean NOT NULL DEFAULT false,
  import_ref    text,
  metadata      jsonb NOT NULL DEFAULT '{}'
);

-- ============ grants (explicit, per object) ============

-- Connector: undo by ID deletes derived rows; raw_inbox stays insert-only.
GRANT SELECT, INSERT                 ON raw_inbox       TO core_rw;
GRANT SELECT, INSERT, UPDATE, DELETE ON thoughts        TO core_rw;
GRANT SELECT, INSERT, UPDATE, DELETE ON thought_updates TO core_rw;
GRANT SELECT, INSERT, UPDATE, DELETE ON thought_links   TO core_rw;

GRANT USAGE ON SCHEMA private TO core_rw;
GRANT SELECT, INSERT, UPDATE, DELETE ON private.entries TO core_rw;

-- NocoDB: never raw_inbox, never the private schema.

COMMIT;
